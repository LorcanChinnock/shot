#!/bin/sh
# Syncs Resources/Localizable.xcstrings with the strings the last build extracted (see Package.swift): adds new ones
# and drops ones the source no longer uses. --check changes nothing and fails when the catalog is out of date, so a
# string can't ship without an entry to translate. It also writes the English table that ShotCore reads where there's no
# String(localized:), on Linux (Sources/ShotCore/ShotLocalized.swift).
set -eu
cd "$(dirname "$0")/.."

check=false
[ "${1:-}" = --check ] && check=true
catalog=Resources/Localizable.xcstrings
table=Sources/ShotCore/LocalizableEnglish.swift
if [ ! -d .build/stringsdata ]; then
    echo "No extracted strings in .build/stringsdata; run swift build first." >&2
    exit 1
fi

# A deleted or renamed source file leaves its old .stringsdata behind, so take only those whose source still exists.
set --
for data in .build/stringsdata/*/*.stringsdata; do
    if [ -f "$(plutil -extract source raw -o - "$data")" ]; then
        set -- "$@" --stringsdata "$data"
    fi
done

# sync only takes strings from the table named like the catalog, so the copy keeps its name.
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp "$catalog" "$work/Localizable.xcstrings"
xcrun xcstringstool sync "$work/Localizable.xcstrings" "$@"

# The English text of each key whose text isn't the key itself (positional arguments, plurals), as its plural forms.
# JSON in a raw string, because a dictionary literal this size is slow to type-check.
{
    echo "// Generated by scripts/strings.sh from $catalog; run make strings rather than editing it."
    echo '#if !canImport(Darwin)'
    echo 'import Foundation'
    echo ''
    echo 'let localizableEnglish: [String: [String: String]] = try! JSONDecoder().decode([String: [String: String]].self, from: Data(#"""'
    jq --sort-keys '.strings | to_entries | map(
        .key as $key | .value.localizations.en | select(. != null)
        | {key: $key, value: (if .variations.plural then .variations.plural | map_values(.stringUnit.value) else {other: .stringUnit.value} end)}
        | select(.value != {other: $key})
    ) | from_entries' "$work/Localizable.xcstrings"
    echo '"""#.utf8))'
    echo '#endif'
} > "$work/LocalizableEnglish.swift"

if ! $check; then
    cp "$work/Localizable.xcstrings" "$catalog"
    cp "$work/LocalizableEnglish.swift" "$table"
    exit 0
fi

if ! cmp -s "$catalog" "$work/Localizable.xcstrings"; then
    echo "$catalog is out of date; run make strings and commit it. Strings added (>) and dropped (<):"
    xcrun xcstringstool print "$catalog" | sort > "$work/before"
    xcrun xcstringstool print "$work/Localizable.xcstrings" | sort > "$work/after"
    diff "$work/before" "$work/after" || true
    exit 1
fi
if ! cmp -s "$table" "$work/LocalizableEnglish.swift"; then
    echo "$table is out of date; run make strings and commit it."
    exit 1
fi

# sync keeps a string the source dropped when it has translations, marked stale.
stale=$(jq -r '.strings | to_entries[] | select(.value.extractionState == "stale") | .key' "$catalog")
if [ -n "$stale" ]; then
    echo "$catalog has strings the app no longer uses; delete these, which it marks stale:"
    echo "$stale"
    exit 1
fi
